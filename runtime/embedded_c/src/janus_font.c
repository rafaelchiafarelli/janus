const uint8_t *janus_font_glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c == ' ') return GLYPHS[0];
    if (c >= 'A' && c <= 'Z') return GLYPHS[1 + (c - 'A')];
    return NULL;
}
